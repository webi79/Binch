function countryName(iso) {
  return COUNTRY_NAMES[iso] ?? iso;
}

const csv = readFileSync(CSV_PATH, "utf-8");
const rows = parseCSV(csv);

const airports = rows
  .filter(
    (r) =>
      r.scheduled_service === "yes" &&
      r.iata_code.length === 3 &&
      (r.type === "large_airport" || r.type === "medium_airport"),
  )
  .map((r) => ({
    iata: r.iata_code,
    name: r.name,
    city: r.municipality || r.name,
    country: countryName(r.iso_country),
    latitude: parseFloat(r.latitude_deg),
    longitude: parseFloat(r.longitude_deg),
  }))
  .filter(
    (a) =>
      Number.isFinite(a.latitude) &&
      Number.isFinite(a.longitude) &&
      a.latitude >= -90 &&
      a.latitude <= 90 &&
      a.longitude >= -180 &&
      a.longitude <= 180,
  )
  .sort((a, b) => a.iata.localeCompare(b.iata));

console.log(`Parsed ${airports.length} airports.`);

